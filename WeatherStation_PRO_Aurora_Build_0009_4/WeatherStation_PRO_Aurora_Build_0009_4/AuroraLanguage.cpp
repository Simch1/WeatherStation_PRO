AuroraLanguage::AuroraLanguage()
  : _language(LANGUAGE_ITALIAN) {}

void AuroraLanguage::setLanguage(
  AuroraLanguageId language
) {
  _language = language;
}

AuroraLanguageId AuroraLanguage::language() const {
  return _language;
}

const char* AuroraLanguage::text(
  AuroraTextId id
) const {
  if (id >= TEXT_COUNT) {
    return "";
  }

  return _language == LANGUAGE_ENGLISH
    ? ENGLISH_TEXTS[id]
    : ITALIAN_TEXTS[id];
}
